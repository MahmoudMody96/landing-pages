#!/usr/bin/env python3
"""Inject schema.org JSON-LD (LocalBusiness) into landing pages.

DEPRECATED: JSON-LD is now rendered by tools/pagekit.py from each record's
`jsonld` input at gen time. Running this script edits src/*.html by hand and
will flip `gen_pages.py --check` from PASS to MISMATCH. Kept for reference
only (and for bootstrapping brand-new cities before they have records).
Do NOT run on generated pages.

Reads Google-sourced data (selected_30.json, hours_data.json, hero_audit.json)
and writes one <script type="application/ld+json"> block per page, marked
with JSONLD-START/END comments. Idempotent: reruns replace the block.

  python tools/inject_seo.py            # all Riyadh pages
  python tools/inject_seo.py --check    # verify only, no writes
  python tools/inject_seo.py --dir=src/cities/ae-dubai --base-url=https://dubai.aidy.site/ae/dubai

Rules: unparseable hours are SKIPPED (reported loudly), never fabricated.
Addresses fall back to plain Text when the parts don't parse.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES_DIR = os.path.join(ROOT, 'src', 'cities', 'sa-riyadh')
BASE_URL = 'https://riyadh.aidy.site/sa/riyadh'

for _arg in sys.argv[1:]:
    if _arg.startswith('--dir='):
        PAGES_DIR = os.path.join(ROOT, _arg.split('=', 1)[1])
    elif _arg.startswith('--base-url='):
        BASE_URL = _arg.split('=', 1)[1].rstrip('/')

AR_DAY = {
    'السبت': 'Saturday', 'الأحد': 'Sunday', 'الاثنين': 'Monday',
    'الثلاثاء': 'Tuesday', 'الأربعاء': 'Wednesday',
    'الخميس': 'Thursday', 'الجمعة': 'Friday',
}
DAY_ORDER = ['Monday', 'Tuesday', 'Wednesday', 'Thursday',
             'Friday', 'Saturday', 'Sunday']

NICHE_TYPE = {
    'coffee': 'CafeOrCoffeeShop',
    'barbershop': 'HairSalon',   # closest standard type; no Barbershop in schema.org
    'beauty_salon': 'BeautySalon',
    'nail_salon': 'NailSalon',
    'gym': 'ExerciseGym',
    'auto_repair': 'AutoRepair',
}

RANGE_RE = re.compile(
    r'^\s*(\d{1,2})(?::(\d{2}))?\s*(AM|PM)?\s*[–\-—]\s*'
    r'(\d{1,2})(?::(\d{2}))?\s*(AM|PM)\s*$')


def to24(h, mi, mer):
    h = int(h)
    mi = int(mi or 0)
    if mer == 'AM':
        h = 0 if h == 12 else h
    else:
        h = 12 if h == 12 else h + 12
    return '%02d:%02d' % (h, mi)


def parse_hours(value):
    """Return list of (opens, closes), [] for closed, or None if unparseable."""
    v = (value or '').strip()
    if not v or v.lower() == 'closed':
        return []
    if v.lower() == 'open 24 hours':
        return [('00:00', '23:59')]
    specs = []
    for part in v.split(','):
        m = RANGE_RE.match(part.strip())
        if not m:
            return None
        h1, m1, mer1, h2, m2, mer2 = m.groups()
        specs.append((to24(h1, m1, mer1 or mer2), to24(h2, m2, mer2)))
    return specs


def schema_type(niche, category):
    if niche in NICHE_TYPE:
        return NICHE_TYPE[niche]
    cat = (category or '').lower()
    if 'nail' in cat:
        return 'NailSalon'
    if 'beauty' in cat:
        return 'BeautySalon'
    if 'barber' in cat or 'hair' in cat:
        return 'HairSalon'
    if 'coffee' in cat or 'cafe' in cat:
        return 'CafeOrCoffeeShop'
    if 'gym' in cat or 'fitness' in cat:
        return 'ExerciseGym'
    if 'sport' in cat:
        return 'SportsActivityLocation'
    if 'car' in cat or 'auto' in cat or 'maintenance' in cat:
        return 'AutoRepair'
    return 'LocalBusiness'


def build_address(raw):
    parts = [p.strip() for p in (raw or '').split(',') if p.strip()]
    locality = next((p for p in parts if 'riyadh' in p.lower()), None)
    if locality is None:
        return raw.strip()  # Text fallback — never fabricate parts
    street = parts[0] if parts[0].lower() != locality.lower() else ''
    postal = re.search(r'\d{5}', locality)
    addr = {'@type': 'PostalAddress', 'addressLocality': 'Riyadh',
            'addressCountry': 'SA'}
    if street:
        addr['streetAddress'] = street
    if postal:
        addr['postalCode'] = postal.group(0)
    return addr


def digits(s):
    return re.sub(r'\D', '', s or '')


START = '<!-- JSONLD-START (generated by tools/inject_seo.py — do not hand-edit) -->'
END = '<!-- JSONLD-END -->'
PATTERN = re.compile(re.escape(START) + r'.*?' + re.escape(END), re.S)


def build_block(business, hours_row, hero_url, slug):
    hero_niche = None
    m = re.search(r'/hero/(\w+)\.jpg', hero_url or '')
    if m:
        hero_niche = m.group(1)
    phone = (hours_row.get('phone_verified') or hours_row.get('phone_input')
             or business.get('phone') or '')
    specs = []
    skipped = []
    for ar_day, day in AR_DAY.items():
        parsed = parse_hours((hours_row.get('hours') or {}).get(ar_day, ''))
        if parsed is None:
            skipped.append(ar_day)
            continue
        for opens, closes in parsed:
            specs.append({'@type': 'OpeningHoursSpecification',
                          'dayOfWeek': day,
                          'opens': opens, 'closes': closes})
    specs.sort(key=lambda s: (DAY_ORDER.index(s['dayOfWeek']), s['opens']))
    doc = {
        '@context': 'https://schema.org',
        '@type': schema_type(hero_niche, business.get('category')),
        'name': business.get('name'),
        'image': hero_url,
        'url': '%s/%s.html' % (BASE_URL, slug),
        'telephone': '+' + digits(phone),
        'address': build_address(business.get('address', '')),
        'aggregateRating': {
            '@type': 'AggregateRating',
            'ratingValue': float(business.get('rating', 0)),
            'reviewCount': int(business.get('reviewCount', 0)),
        },
    }
    if (hours_row.get('href') or '').startswith('http'):
        doc['sameAs'] = [hours_row['href']]
    if specs:
        doc['openingHoursSpecification'] = specs
    block = (START + '\n<script type="application/ld+json">\n'
             + json.dumps(doc, ensure_ascii=False, indent=2)
             + '\n</script>\n' + END)
    return block, skipped


def main():
    check_only = '--check' in sys.argv
    sel = json.load(open(os.path.join(ROOT, 'data', 'selected_30.json'),
                         encoding='utf-8'))
    hours = json.load(open(os.path.join(ROOT, 'data', 'hours_data.json'),
                           encoding='utf-8'))
    audit = json.load(open(os.path.join(ROOT, 'hero_audit.json'),
                           encoding='utf-8'))
    by_name = {b['name']: b for b in sel}
    hours_by_name = {h['name']: h for h in hours}
    hero_by_slug = {a['slug']: a['url'] for a in audit}

    changed, skipped_total, errors = 0, {}, []
    for fname in sorted(os.listdir(PAGES_DIR)):
        if not fname.endswith('.html'):
            continue
        slug = fname[:-5]
        name = next((a['name'] for a in audit if a['slug'] == slug), None)
        if name is None or name not in by_name or name not in hours_by_name:
            errors.append('%s: no source data' % slug)
            continue
        block, skipped = build_block(by_name[name], hours_by_name[name],
                                     hero_by_slug.get(slug, ''), slug)
        if skipped:
            skipped_total[slug] = skipped
        path = os.path.join(PAGES_DIR, fname)
        html = open(path, encoding='utf-8').read()
        if html.count('</head>') != 1:
            errors.append('%s: </head> count != 1' % slug)
            continue
        if PATTERN.search(html):
            new_html = PATTERN.sub(lambda _: block, html)
        else:
            new_html = html.replace('</head>', block + '\n</head>')
        if new_html != html and not check_only:
            open(path, 'w', encoding='utf-8', newline='\n').write(new_html)
            changed += 1

    print('pages: %d, %s: %d' % (
        len([f for f in os.listdir(PAGES_DIR) if f.endswith('.html')]),
        'verified' if check_only else 'updated', changed))
    if skipped_total:
        print('SKIPPED-DAYS (unparseable hours, left out of JSON-LD):')
        for slug, days in sorted(skipped_total.items()):
            print('  %s: %s' % (slug, days))
    else:
        print('all hours parsed, nothing skipped')
    if errors:
        print('ERRORS:')
        for e in errors:
            print('  ' + e)
        sys.exit(1)


if __name__ == '__main__':
    main()
